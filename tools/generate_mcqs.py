def draw_footer(canvas, doc):

    page_width, _ = A4

    left = style.MARGIN_LEFT

    right = (
        page_width
        - style.MARGIN_RIGHT
    )

    footer_y = 4.5 * style.mm

    canvas.setFont(
        style.BODY_FONT,
        style.FOOTER_FONT_SIZE,
    )

    canvas.setFillColor(
        style.FOOTER_COLOR
    )

    canvas.drawString(
        left,
        footer_y,
        style.BRAND_NAME,
    )

    canvas.drawRightString(
        right,
        footer_y,
        f"Page {doc.page}",
    )


def draw_page(canvas, doc):

    canvas.saveState()

    draw_header(
        canvas,
        doc,
    )

    draw_footer(
        canvas,
        doc,
    )

    canvas.restoreState()


