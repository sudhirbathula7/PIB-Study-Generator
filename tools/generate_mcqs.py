def mcq_question_paragraph(number, question):
    """
    Render:
        1. Which of the following...
    """

    if not question:
        return None

    if number:

        text = (
            f"<b>{number}.</b> "
            f"{safe_inline(question)}"
        )

    else:

        text = safe_inline(
            question
        )

    return Paragraph(
        text,
        style.MCQ_QUESTION_STYLE,
    )


def mcq_statement_paragraph(
    number,
    statement,
):
    """
    Render:
        Statement 1: ...
    """

    return Paragraph(
        (
            f"<b>Statement {number}:</b> "
            f"{safe_inline(statement)}"
        ),
        style.MCQ_STATEMENT_STYLE,
    )


def build_options_table(options):
    """
    Render MCQ options in a clean 2-column grid.

    Example:

    (a) Option A                 (b) Option B
    (c) Option C                 (d) Option D
    """

    if not options:
        return None

    content_width = (
        A4[0]
        - style.MARGIN_LEFT
        - style.MARGIN_RIGHT
    )

    main_width = (
        content_width
        * style.CONTENT_COLUMN_RATIO
        - style.CONTENT_RIGHT_PADDING
    )

    column_width = (
        main_width / 2
    )

    cells = []

    for label, option_text in options:

        cell = Paragraph(
            (
                f"<b>{safe_inline(label)}</b> "
                f"{safe_inline(option_text)}"
            ),
            style.MCQ_OPTION_STYLE,
        )

        cells.append(cell)

    rows = []

    for index in range(
        0,
        len(cells),
        2,
    ):

        left = cells[index]

        if index + 1 < len(cells):
            right = cells[index + 1]
        else:
            right = Paragraph(
                "",
                style.MCQ_OPTION_STYLE,
            )

        rows.append(
            [
                left,
                right,
            ]
        )

    table = Table(
        rows,
        colWidths=[
            column_width,
            column_width,
        ],
        hAlign="LEFT",
    )

    table.setStyle(
        TableStyle(
            [
                (
                    "VALIGN",
                    (0, 0),
                    (-1, -1),
                    "TOP",
                ),
                (
                    "LEFTPADDING",
                    (0, 0),
                    (-1, -1),
                    0,
                ),
                (
                    "RIGHTPADDING",
                    (0, 0),
                    (-1, -1),
                    style.MCQ_OPTION_GAP,
                ),
                (
                    "TOPPADDING",
                    (0, 0),
                    (-1, -1),
                    0,
                ),
                (
                    "BOTTOMPADDING",
                    (0, 0),
                    (-1, -1),
                    1,
                ),
            ]
        )
    )

    return table


