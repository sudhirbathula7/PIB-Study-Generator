def open_pdf(path):
    """
    Open generated PDF using the default Windows PDF viewer.
    """

    try:
        webbrowser.open(
            Path(path).resolve().as_uri()
        )
    except Exception:
        pass


def normalize_lines(data):
    if data is None:
        return []

    text = str(data)

    text = text.replace(
        "\r\n",
        "\n",
    ).replace(
        "\r",
        "\n",
    )

    return [
        line.rstrip()
        for line in text.split("\n")
    ]


# ============================================================
# HTML / MARKDOWN CLEANING
# ============================================================

def strip_html(text):
    """
    Remove accidental HTML generated by the AI.

    This prevents tags such as:
        <div>
        <span>
        <br>
        <strong>
    from appearing in the final PDF.
    """

    text = str(text)

    text = re.sub(
        r"<br\s*/?>",
        " ",
        text,
        flags=re.IGNORECASE,
    )

    text = re.sub(
        r"</p\s*>",
        " ",
        text,
        flags=re.IGNORECASE,
    )

    text = re.sub(
        r"<[^>]+>",
        "",
        text,
    )

    return html.unescape(text)


def clean_text(text):
    """
    Plain text cleanup for MCQ parser.
    """

    text = strip_html(text)

    # Remove markdown emphasis markers.
    text = re.sub(
        r"\*\*([^*]+)\*\*",
        r"\1",
        text,
    )

    text = re.sub(
        r"__([^_]+)__",
        r"\1",
        text,
    )

    text = re.sub(
        r"(?<!\*)\*([^*]+)\*(?!\*)",
        r"\1",
        text,
    )

    text = re.sub(
        r"(?<!_)_([^_]+)_(?!_)",
        r"\1",
        text,
    )

    # Collapse excessive whitespace.
    text = re.sub(
        r"[ \t]+",
        " ",
        text,
    )

    return text.strip()


# ============================================================
# MCQ BLOCK SPLITTING
# ============================================================

def split_mcq_blocks(text):
    """
    Split MCQ content into individual questions.

    A question begins ONLY when a line starts with:
        1.
        2.
        3.

    This is intentionally strict so that:
        Statement 1:
        Statement 2:
        (a)
        (b)
    are NOT incorrectly treated as new questions.
    """

    lines = normalize_lines(text)

    starts = []

    for index, line in enumerate(lines):

        if re.match(
            r"^\s*\d+\.\s+\S",
            line,
        ):
            starts.append(index)

    if not starts:

        stripped = str(
            text or ""
        ).strip()

        return [stripped] if stripped else []

    blocks = []

    for position, start in enumerate(starts):

        if position + 1 < len(starts):
            end = starts[position + 1]
        else:
            end = len(lines)

        block = "\n".join(
            lines[start:end]
        ).strip()

        if block:
            blocks.append(block)

    return blocks


# ============================================================
# QUESTION NUMBER
# ============================================================

def extract_question_number(block):
    """
    Extract:
        1. Question text

    into:
        ("1", "Question text")
    """

    match = re.match(
        r"^\s*(\d+)\.\s*(.*)$",
        block,
        flags=re.DOTALL,
    )

    if not match:
        return "", block.strip()

    return (
        match.group(1),
        match.group(2).strip(),
    )


# ============================================================
# ANSWER / EXPLANATION
# ============================================================

def split_answer_explanation(text):
    """
    Separate:

        Answer: (b)
        Explanation: ...

    from the question.
    """

    answer_match = re.search(
        r"(?im)^\s*Answer\s*:\s*(.+?)\s*$",
        text,
    )

    if not answer_match:

        explanation_match = re.search(
            r"(?im)^\s*Explanation\s*:\s*",
            text,
        )

        if explanation_match:

            question_part = (
                text[:explanation_match.start()]
                .strip()
            )

            explanation = (
                text[
                    explanation_match.end():
                ].strip()
            )

            return (
                question_part,
                "",
                explanation,
            )

        return (
            text.strip(),
            "",
            "",
        )

    question_part = (
        text[:answer_match.start()]
        .strip()
    )

    answer = (
        answer_match.group(1)
        .strip()
    )

    remaining = (
        text[answer_match.end():]
        .strip()
    )

    explanation_match = re.search(
        r"(?im)^\s*Explanation\s*:\s*",
        remaining,
    )

    if explanation_match:

        explanation = (
            remaining[
                explanation_match.end():
            ].strip()
        )

    else:

        explanation = remaining

    return (
        question_part,
        answer,
        explanation,
    )


# ============================================================
# STATEMENTS
# ============================================================

def extract_statements(text):
    """
    Extract:

        Statement 1: ...
        Statement 2: ...
        Statement 3: ...

    without confusing them with question numbers.
    """

    pattern = re.compile(
        r"(?im)^\s*Statement\s+(\d+)\s*:\s*"
    )

    matches = list(
        pattern.finditer(text)
    )

    if not matches:
        return [], text

    statements = []

    for index, match in enumerate(matches):

        start = match.end()

        if index + 1 < len(matches):

            end = matches[
                index + 1
            ].start()

        else:

            # Stop at the first option or answer.
            remainder = text[start:]

            stop_match = re.search(
                r"(?im)^\s*"
                r"(?:"
                r"\([abcd]\)"
                r"|Answer\s*:"
                r"|Explanation\s*:"
                r")",
                remainder,
            )

            if stop_match:
                end = (
                    start
                    + stop_match.start()
                )
            else:
                end = len(text)

        statement_text = text[
            start:end
        ].strip()

        statement_text = clean_text(
            statement_text
        )

        statements.append(
            (
                match.group(1),
                statement_text,
            )
        )

    # Remove statement block from question text.
    first_start = matches[0].start()

    before = text[
        :first_start
    ].strip()

    after = text[
        matches[-1].end():
    ]

    # Remove the last statement body from the
    # remaining question text.
    last_stop = re.search(
        r"(?im)^\s*"
        r"(?:"
        r"\([abcd]\)"
        r"|Answer\s*:"
        r"|Explanation\s*:"
        r")",
        after,
    )

    if last_stop:

        remaining = after[
            last_stop.start():
        ].strip()

    else:

        remaining = ""

    if before and remaining:
        question_text = (
            before
            + "\n"
            + remaining
        )
    elif before:
        question_text = before
    else:
        question_text = remaining

    return (
        statements,
        question_text.strip(),
    )


# ============================================================
# OPTIONS
# ============================================================

def extract_options(text):
    """
    Extract options:

        (a) ...
        (b) ...
        (c) ...
        (d) ...

    Options may be on separate lines or accidentally placed
    on the same line.
    """

    pattern = re.compile(
        r"(?im)(?:^|\s)"
        r"(\([abcd]\))"
        r"\s*"
    )

    matches = list(
        pattern.finditer(text)
    )

    if not matches:
        return [], text.strip()

    options = []

    for index, match in enumerate(matches):

        label = (
            match.group(1)
            .lower()
        )

        start = match.end()

        if index + 1 < len(matches):

            end = matches[
                index + 1
            ].start()

        else:

            end = len(text)

        option_text = text[
            start:end
        ].strip()

        option_text = clean_text(
            option_text
        )

        options.append(
            (
                label,
                option_text,
            )
        )

    question_text = text[
        :matches[0].start()
    ].strip()

    return (
        options,
        question_text,
    )


# ============================================================
# PARSE ONE MCQ
# ============================================================

def parse_mcq(block):
    """
    Convert a raw MCQ block into a structured dictionary.
    """

    number, body = (
        extract_question_number(
            block
        )
    )

    (
        main_content,
        answer,
        explanation,
    ) = split_answer_explanation(
        body
    )

    (
        statements,
        main_without_statements,
    ) = extract_statements(
        main_content
    )

    (
        options,
        question_text,
    ) = extract_options(
        main_without_statements
    )

    question_text = clean_text(
        question_text
    )

    answer = clean_text(
        answer
    )

    explanation = clean_text(
        explanation
    )

    return {
        "number": number,
        "question": question_text,
        "statements": statements,
        "options": options,
        "answer": answer,
        "explanation": explanation,
    }


