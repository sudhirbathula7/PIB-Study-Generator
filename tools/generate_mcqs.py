def generate_mcq_pdf(
    mcq_data,
    output_path=None,
    yymmdd_str="",
):
    """
    Generate compact MCQ PDF.

    Layout is identical to Summary / Quick Revision.
    """

    if output_path is None:
        output_path = Path(
            "mcqs.pdf"
        )

    output_path = Path(
        output_path
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    date_text = format_date_str(
        yymmdd_str
    )

    document = PIBMCQDocTemplate(
        str(output_path),
        header_title=style.BRAND_NAME,
        date_text=date_text,
    )

    raw_text = str(
        mcq_data or ""
    ).strip()

    blocks = split_mcq_blocks(
        raw_text
    )

    story = []

    # --------------------------------------------------------
    # Parse and render each question.
    # --------------------------------------------------------

    for block in blocks:

        parsed = parse_mcq(
            block
        )

        question_story = (
            build_question_story(
                parsed
            )
        )

        if question_story:

            # Keep the individual question together whenever
            # the question is small enough for one page.
            story.append(
                KeepTogether(
                    question_story
                )
            )

    # --------------------------------------------------------
    # Empty MCQ input
    # --------------------------------------------------------

    if not story:

        story.append(
            Paragraph(
                "No MCQs available.",
                style.BODY_STYLE,
            )
        )

    # --------------------------------------------------------
    # Build PDF
    # --------------------------------------------------------

    document.build(
        story
    )

    return str(
        output_path
    )


