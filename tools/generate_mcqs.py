def draw_header(canvas, doc):

    page_width, page_height = A4

    left = style.MARGIN_LEFT

    right = (
        page_width
        - style.MARGIN_RIGHT
    )

    top = (
        page_height
        - style.MARGIN_TOP
    )

    # --------------------------------------------------------
    # Logo
    # --------------------------------------------------------

    logo_path = get_logo_path()

    if logo_path:

        try:

            from reportlab.lib.utils import (
                ImageReader
            )

            image = ImageReader(
                str(logo_path)
            )

            image_width, image_height = (
                image.getSize()
            )

            target_width = (
                style.HEADER_LOGO_WIDTH
            )

            target_height = (
                target_width
                * image_height
                / image_width
            )

            canvas.drawImage(
                image,
                left,
                top - target_height,
                width=target_width,
                height=target_height,
                preserveAspectRatio=True,
                mask="auto",
            )

        except Exception:
            pass

    # --------------------------------------------------------
    # Header title
    # --------------------------------------------------------

    title_x = (
        left
        + style.HEADER_LOGO_CELL_WIDTH
    )

    title = getattr(
        doc,
        "_pib_header_title",
        style.BRAND_NAME,
    )

    canvas.setFont(
        style.BODY_BOLD_FONT,
        style.HEADER_TITLE_SIZE,
    )

    canvas.setFillColor(
        style.HEADER_TITLE_COLOR
    )

    max_width = (
        right
        - title_x
    )

    words = title.split()

    lines = []
    current = ""

    for word in words:

        candidate = (
            word
            if not current
            else f"{current} {word}"
        )

        if (
            canvas.stringWidth(
                candidate,
                style.BODY_BOLD_FONT,
                style.HEADER_TITLE_SIZE,
            )
            <= max_width
        ):

            current = candidate

        else:

            if current:
                lines.append(
                    current
                )

            current = word

    if current:
        lines.append(
            current
        )

    title_y = top - 12

    for line in lines[:2]:

        canvas.drawString(
            title_x,
            title_y,
            line,
        )

        title_y -= (
            style.HEADER_TITLE_LEADING
        )

    # --------------------------------------------------------
    # Blue divider
    # --------------------------------------------------------

    divider_y = (
        top
        - max(
            30,
            len(lines[:2])
            * style.HEADER_TITLE_LEADING
            + 8,
        )
    )

    canvas.setStrokeColor(
        style.HEADER_DIVIDER_COLOR
    )

    canvas.setLineWidth(
        style.HEADER_DIVIDER_WIDTH
    )

    canvas.line(
        left,
        divider_y,
        right,
        divider_y,
    )

    # --------------------------------------------------------
    # Date
    # --------------------------------------------------------

    date_text = getattr(
        doc,
        "_pib_date_text",
        "",
    )

    if date_text:

        canvas.setFont(
            style.BODY_FONT,
            7.5,
        )

        canvas.setFillColor(
            style.NOTES_TEXT_COLOR
        )

        canvas.drawRightString(
            right,
            divider_y - 10,
            date_text,
        )

    # --------------------------------------------------------
    # Notes separator
    # --------------------------------------------------------

    usable_width = (
        page_width
        - style.MARGIN_LEFT
        - style.MARGIN_RIGHT
    )

    separator_x = (
        style.MARGIN_LEFT
        + usable_width
        * style.CONTENT_COLUMN_RATIO
    )

    canvas.setStrokeColor(
        style.NOTES_SEPARATOR_COLOR
    )

    canvas.setLineWidth(
        style.NOTES_SEPARATOR_WIDTH
    )

    canvas.setDash(
        2,
        2,
    )

    canvas.line(
        separator_x,
        divider_y - 3,
        separator_x,
        style.MARGIN_BOTTOM + 3,
    )

    canvas.setDash()

    # --------------------------------------------------------
    # Notes label
    # --------------------------------------------------------

    notes_center = (
        separator_x
        + usable_width
        * style.NOTES_COLUMN_RATIO
        / 2
    )

    canvas.setFont(
        style.BODY_FONT,
        style.NOTES_TEXT_SIZE,
    )

    canvas.setFillColor(
        style.NOTES_TEXT_COLOR
    )

    canvas.drawCentredString(
        notes_center,
        divider_y - 16,
        "NOTES",
    )


