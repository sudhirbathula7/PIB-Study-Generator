def build_question_story(question):
    """
    Build one complete MCQ.

    The question, statements, options, answer and explanation
    are kept together where ReportLab can fit them.
    """

    elements = []

    number = question.get(
        "number",
        "",
    )

    question_text = question.get(
        "question",
        "",
    )

    statements = question.get(
        "statements",
        [],
    )

    options = question.get(
        "options",
        [],
    )

    answer = question.get(
        "answer",
        "",
    )

    explanation = question.get(
        "explanation",
        "",
    )

    # --------------------------------------------------------
    # Question
    # --------------------------------------------------------

    question_paragraph = (
        mcq_question_paragraph(
            number,
            question_text,
        )
    )

    if question_paragraph:

        elements.append(
            question_paragraph
        )

    # --------------------------------------------------------
    # Statements
    # --------------------------------------------------------

    for statement_number, statement in statements:

        elements.append(
            mcq_statement_paragraph(
                statement_number,
                statement,
            )
        )

    # --------------------------------------------------------
    # Options
    # --------------------------------------------------------

    options_table = (
        build_options_table(
            options
        )
    )

    if options_table:

        elements.append(
            Spacer(
                1,
                1,
            )
        )

        elements.append(
            options_table
        )

    # --------------------------------------------------------
    # Answer
    # --------------------------------------------------------

    answer_box = (
        build_answer_box(
            answer
        )
    )

    if answer_box:

        elements.append(
            Spacer(
                1,
                2,
            )
        )

        elements.append(
            answer_box
        )

    # --------------------------------------------------------
    # Explanation
    # --------------------------------------------------------

    explanation_box = (
        build_explanation_box(
            explanation
        )
    )

    if explanation_box:

        elements.append(
            Spacer(
                1,
                2,
            )
        )

        elements.append(
            explanation_box
        )

    # --------------------------------------------------------
    # Small gap before next question
    # --------------------------------------------------------

    elements.append(
        Spacer(
            1,
            style.MCQ_BLOCK_SPACE_AFTER,
        )
    )

    return elements


